/**
 * Peer range for `@deepseek-ai/dsh-*`: keep the legacy rc.6–rc.8 union and
 * pin any newer tested Host exactly. Must not widen to 0.1.0-rc.9 or
 * 0.1.1-rc.1 when those versions are not the tested target.
 */

export const DSH_LEGACY_PEER_MAXIMUM = '0.1.0-rc.8'

function parseVersion(value) {
  const match = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-([0-9A-Za-z.-]+))?$/u.exec(value.trim())
  if (match === null) return undefined
  return {
    major: Number(match[1]),
    minor: Number(match[2]),
    patch: Number(match[3]),
    pre: (match[4] ?? '').split('.').filter(part => part !== ''),
  }
}

/**
 * Compare two dsh versions. Returns negative when `left` is older.
 * @param left - candidate version.
 * @param right - baseline version.
 */
export function compareDshVersions(left, right) {
  const a = parseVersion(left)
  const b = parseVersion(right)
  if (a === undefined || b === undefined) return undefined
  if (a.major !== b.major) return a.major - b.major
  if (a.minor !== b.minor) return a.minor - b.minor
  if (a.patch !== b.patch) return a.patch - b.patch
  if (a.pre.length === 0 && b.pre.length === 0) return 0
  if (a.pre.length === 0) return 1
  if (b.pre.length === 0) return -1
  const text = (part) => (/^(0|[1-9]\d*)$/u.test(part) ? Number(part) : part)
  const length = Math.max(a.pre.length, b.pre.length)
  for (let index = 0; index < length; index += 1) {
    if (a.pre[index] === undefined) return -1
    if (b.pre[index] === undefined) return 1
    const x = text(a.pre[index])
    const y = text(b.pre[index])
    if (x === y) continue
    if (typeof x === 'number' && typeof y === 'number') return x - y
    if (typeof x === 'number') return -1
    if (typeof y === 'number') return 1
    return x < y ? -1 : 1
  }
  return 0
}

/**
 * Optional peer range generated by `scripts/bump-dsh.mjs`.
 * @param minimumVersion - `dsh.compatibility.minimum`.
 * @param testedVersion - new `dsh.compatibility.tested`.
 * @param legacyMaximum - last Host on the 0.1.0-rc line still in the union.
 */
export function dshPeerRange(minimumVersion, testedVersion, legacyMaximum = DSH_LEGACY_PEER_MAXIMUM) {
  const legacy = `>=${minimumVersion} <=${legacyMaximum}`
  const vsMin = compareDshVersions(testedVersion, minimumVersion)
  const vsLegacy = compareDshVersions(testedVersion, legacyMaximum)
  if (vsMin !== undefined && vsLegacy !== undefined && vsMin >= 0 && vsLegacy <= 0) {
    return legacy
  }
  return `${legacy} || ${testedVersion}`
}
