function requestedEnvironmentLocale(env: NodeJS.ProcessEnv): LocaleId {
  const candidates = [
    env.LC_ALL,
    env.LC_MESSAGES,
    ...(env.LANGUAGE?.split(':') ?? []),
    env.LANG,
  ]
  for (const candidate of candidates) {
    const normalized = candidate?.trim().toLowerCase()
    if (normalized === undefined || normalized === '') continue
    if (/^en(?:[-_.@]|$)/u.test(normalized)) return 'en'
    if (/^zh(?:[-_.@]|$)/u.test(normalized)) return 'zh'
  }
  return DEFAULT_TUI_LOCALE
}

/** Resolve the pre-connection CLI language from POSIX locale variables. */
export function localeFromEnvironment(env: NodeJS.ProcessEnv = process.env): LocaleId {
  return requestedEnvironmentLocale(env)
}

function localeValue(document: TuiSettingsDocument): LocaleSettings {
  if (typeof document.value !== 'object' || document.value === null || Array.isArray(document.value)) {
    throw new Error('Harness locale Settings value must be an object')
  }
  const value = document.value as Readonly<Record<string, unknown>>
  const preference = value[LOCALE_PREFERENCE_FIELD]
  if (preference === undefined) return {}
  if (!LOCALE_IDS.some(candidate => candidate === preference)) {
    throw new Error(`Harness locale preference is invalid: ${JSON.stringify(preference)}`)
  }
  return { preference: preference as LocaleId }
}

/** Read the current process-local terminal language. */
export function uiLocale(): LocaleId { return currentLocale }

/** Change terminal presentation only; durable state remains in Harness Settings. */
export function setUiLocale(locale: LocaleId): boolean {
  if (!LOCALE_IDS.includes(locale)) throw new Error(`Unsupported locale ${JSON.stringify(locale)}`)
  if (currentLocale === locale) return false
  currentLocale = locale
  return true
}

/** Select one of two authored UI strings at the point where presentation is built. */
export function ui(zh: string, en: string): string {
  return currentLocale === 'en' ? en : zh
}

/** Translate a known legacy Chinese UI string without altering unknown model or provider content. */
export function translateUiText(text: string): string {
  if (currentLocale === 'zh' || text === '') return text
  const exact = ENGLISH_TEXT.get(text)
  if (exact !== undefined) return exact
  for (const entry of ENGLISH_PATTERNS) {
    const match = entry.pattern.exec(text)
    if (match !== null) return entry.replace(...match.slice(1))
  }
  return text
}

/** Find the official locale descriptor registered by the Harness plugin. */
export function localeSettings(documents: readonly TuiSettingsDocument[]): TuiSettingsDocument {
  const document = documents.find(candidate => candidate.namespace === LOCALE_SETTINGS_NAMESPACE)
  if (document === undefined) throw new Error(`Harness did not register Settings namespace ${LOCALE_SETTINGS_NAMESPACE}`)
  return document
}

/** Read the persisted explicit choice, or `auto` when each client chooses its platform language. */
export function languageSelection(document: TuiSettingsDocument): TuiLanguageSelection {
  return localeValue(document).preference ?? 'auto'
}

/** Resolve the terminal language from the shared preference and POSIX locale variables. */
export function localeFromSettings(
  documents: readonly TuiSettingsDocument[],
  env: NodeJS.ProcessEnv = process.env,
): LocaleId {
  return localeValue(localeSettings(documents)).preference ?? localeFromEnvironment(env)
}

/** Persist an explicit or automatic language choice through the Harness Settings service. */
export async function saveLanguage(
  settings: TuiManagementBridge['settings'],
  document: TuiSettingsDocument,
  selection: TuiLanguageSelection,
  env: NodeJS.ProcessEnv = process.env,
): Promise<{ readonly document: TuiSettingsDocument; readonly locale: LocaleId }> {
  const updated = await settings.mutate(
    LOCALE_SETTINGS_NAMESPACE,
    selection === 'auto'
      ? [{ op: 'unset', path: [LOCALE_PREFERENCE_FIELD] }]
      : [{ op: 'set', path: [LOCALE_PREFERENCE_FIELD], value: selection }],
    document.revision,
  )
  const stored = languageSelection(updated)
  if (stored !== selection) {
    throw new Error(`Harness stored an unexpected locale preference ${JSON.stringify(stored)}`)
  }
  return {
    document: updated,
    locale: stored === 'auto' ? localeFromEnvironment(env) : stored,
  }
}
